// Renders every desktop-ui icon component to the SVG body the engine's <icon> draws, into
// ui/kit/icons/catalog.gen.ts. Run after desktop-ui's icons change: `bun run icons`
// (`bun run icons:check` fails when the catalog is stale).

import { join } from "node:path";
import { createElement, type ComponentType } from "react";
import { renderToStaticMarkup } from "react-dom/server";

const ROOT = join(import.meta.dir, "..");
const UI = join(ROOT, "../desktop-ui/src");
const OUT = join(ROOT, "ui/kit/icons/catalog.gen.ts");
const load = (path: string): Promise<Record<string, unknown>> => import(join(UI, path));

type Entry = { view: number; body: string; color?: string };

const ATTRS: Record<string, string> = {
  fill: "fill",
  stroke: "stroke",
  "stroke-width": "stroke-width",
  "stroke-linecap": "stroke-linecap",
  "stroke-linejoin": "stroke-linejoin",
  "fill-rule": "fill-rule",
  "clip-rule": "clip-rule",
  opacity: "opacity",
};

function toEntry(markup: string): Entry {
  const open = markup.match(/^<svg([^>]*)>/);
  if (!open) throw new Error(`not an svg: ${markup.slice(0, 80)}`);
  const attrs = Object.fromEntries([...open[1].matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
  const inner = markup.slice(open[0].length, markup.lastIndexOf("</svg>"));
  const [minX, minY, w, h] = (attrs.viewBox ?? "0 0 24 24").split(/[\s,]+/).map(Number);
  const view = Math.max(w, h);
  const dx = -minX + (view - w) / 2;
  const dy = -minY + (view - h) / 2;
  const paint = Object.entries(ATTRS)
    .filter(([a]) => attrs[a] !== undefined)
    .map(([a, out]) => `${out}="${attrs[a]}"`);
  if (dx || dy) paint.push(`transform="translate(${+dx.toFixed(4)} ${+dy.toFixed(4)})"`);
  const body = paint.length ? `<g ${paint.join(" ")}>${inner}</g>` : inner;
  const color = attrs.style?.match(/(?:^|;)\s*color:\s*([^;]+)/)?.[1]?.trim();
  return { view: +view.toFixed(4), body, ...(color ? { color } : {}) };
}

const render = (C: unknown, props: Record<string, unknown> = {}) => toEntry(renderToStaticMarkup(createElement(C as ComponentType<Record<string, unknown>>, { size: 24, ...props })));

const isComponent = (v: unknown) => typeof v === "function" || (typeof v === "object" && v !== null && "$$typeof" in v);

async function catalog() {
  const groups: Record<string, Record<string, Entry>> = { stella: {}, nav: {}, display: {}, window: {}, brand: {}, mark: {} };

  for (const [name, C] of Object.entries(await load("ui/icons.tsx"))) if (isComponent(C)) groups.stella[name] = render(C);
  for (const [name, C] of Object.entries(await load("ui/nav-icons.tsx"))) if (isComponent(C)) groups.nav[name] = render(C);
  for (const [name, C] of Object.entries(await load("shell/ShellTopBarWindowsIcons.tsx"))) if (isComponent(C)) groups.window[name] = render(C);

  const { DisplayTabIcon } = await load("features/workspace-display/icons.tsx");
  const kinds = (await Bun.file(join(UI, "features/workspace-display/types.ts")).text()).match(/DisplayTabKind =([^;]+);/)![1];
  for (const [, kind] of kinds.matchAll(/"([^"]+)"/g)) groups.display[kind] = render(DisplayTabIcon, { kind });

  const { BRAND_ICON_MARKUP, BRAND_ICON_COLOR_MARKUP } = (await import("@stella/theme/brand-icons")) as Record<string, Record<string, string>>;
  for (const [name, body] of Object.entries(BRAND_ICON_MARKUP)) groups.brand[name] = { view: 24, body: `<g fill="currentColor">${body}</g>` };
  for (const [name, body] of Object.entries(BRAND_ICON_COLOR_MARKUP ?? {})) groups.brand[`${name}-color`] = { view: 24, body };

  const { StellaMark } = await load("ui/stella-mark.tsx");
  groups.mark.stella = render(StellaMark, { size: 64 });
  groups.mark.stellaSmall = render(StellaMark, { size: 16 });
  const { ClaudeLogoIcon } = await load("ui/claude-logo-icon.tsx");
  groups.mark.claude = render(ClaudeLogoIcon, { variant: "mark" });
  groups.mark.claudeTile = render(ClaudeLogoIcon, { variant: "tile" });
  return groups;
}

const groups = await catalog();
let out = "// Generated by scripts/gen-icons.ts from desktop-ui's icon components. Do not edit.\n\n";
out += "export type IconData = { readonly name: string; readonly view: number; readonly body: string; readonly color?: string };\n\n";
for (const [group, entries] of Object.entries(groups)) {
  out += `export const ${group} = {\n`;
  for (const [name, e] of Object.entries(entries)) {
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
    out += `  ${key}: { name: ${JSON.stringify(`${group}/${name}`)}, view: ${e.view}, body: ${JSON.stringify(e.body)}${e.color ? `, color: ${JSON.stringify(e.color)}` : ""} },\n`;
  }
  out += "} as const satisfies Record<string, IconData>;\n\n";
}

const counts = Object.entries(groups).map(([g, e]) => `${g} ${Object.keys(e).length}`).join(", ");
if (process.argv.includes("--check")) {
  const current = await Bun.file(OUT).text().catch(() => "");
  if (current !== out) {
    console.error("ui/kit/icons/catalog.gen.ts is stale: run `bun run icons`");
    process.exit(1);
  }
  console.error(`icons up to date (${counts})`);
} else {
  await Bun.write(OUT, out);
  console.error(`wrote ${OUT} (${counts})`);
}
