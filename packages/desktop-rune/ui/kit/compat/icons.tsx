import { useTokens, type Style } from "../../theme";
import { Icons, withStroke, type IconData } from "../icons";
import { useInk } from "./text";

const TEXT_ONLY = ["lh", "em", "weight", "family", "mono", "textAlign", "textCase", "italic", "nowrap", "lineHeight", "tracking", "underline", "strike", "truncate", "maxLines", "selectable", "placeholderColor"] as const;

export type IconProps = Omit<Style, "size" | "color" | "opacity"> & { size?: number | string; strokeWidth?: number | string; color?: string; className?: string; title?: string; opacity?: number; id?: string; spin?: number; "aria-hidden"?: boolean | "true" | "false"; focusable?: string | boolean };
export type IconComponent = ((props: IconProps) => React.JSX.Element) & { displayName?: string; icon: IconData };

/** desktop-ui's icon component for one catalog icon: `size`, `strokeWidth`, tinted with `color` or the surrounding text colour; other props lay it out as a Rune box. */
export function iconComponent(icon: IconData, name: string): IconComponent {
  const C = (({ size = 24, strokeWidth, color, className: _className, "aria-hidden": _hidden, focusable: _focusable, ...box }: IconProps) => {
    const t = useTokens();
    const ink = useInk();
    const width = strokeWidth === undefined ? undefined : Number(strokeWidth);
    const data = width === undefined || width === 2 ? icon : withStroke(icon, width);
    const rest: Record<string, unknown> = { ...box };
    for (const k of TEXT_ONLY) delete rest[k];
    return <icon {...rest} svg={data.body} name={data.name} view={data.view} size={Number(size)} color={color ?? (icon.color as string | undefined) ?? ink ?? t.c.foreground} />;
  }) as IconComponent;
  C.displayName = name;
  C.icon = icon;
  return C;
}

