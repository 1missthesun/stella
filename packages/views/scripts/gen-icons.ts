// Writes src/icons.gen.ts: every Lucide icon by its kebab-case name (aliases included), as the
// SVG elements inside a 24×24 stroked group. Views name icons the way agents already know them
// (`<Icon name="droplet" />`), and every host draws the same set.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(import.meta.dirname, "..");
const iconsDir = join(dirname(fileURLToPath(import.meta.resolve("lucide-react"))), "..", "esm", "icons");
const attr = (value: unknown) => String(value).replace(/&/gu, "&amp;").replace(/"/gu, "&quot;");

const icons: Record<string, string> = {};
for (const file of readdirSync(iconsDir).filter((f) => f.endsWith(".mjs")).sort()) {
  const mod = (await import(join(iconsDir, file))) as { __iconData?: { node: Array<[string, Record<string, unknown>]> } };
  if (!mod.__iconData) continue;
  const body = mod.__iconData.node
    .map(([tag, attrs]) => `<${tag}${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => ` ${k}="${attr(v)}"`).join("")}/>`)
    .join("");
  icons[file.slice(0, -4)] = body;
}
const names = Object.keys(icons);
const out = `// Generated by scripts/gen-icons.ts from lucide-react (ISC). Do not edit.\n/** Lucide icons by kebab-case name: the elements inside a 24×24 group stroked in currentColor, 2 wide, round caps and joins. */\nexport const VIEW_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(icons)};\n`;
writeFileSync(join(root, "src/icons.gen.ts"), out);
console.log(`${names.length} icons, ${(out.length / 1024).toFixed(0)} KB`);
