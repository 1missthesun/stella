// Writes src/runtime.gen.ts from runtime/runtime.js, so every host (Bun, Metro, browsers) gets
// the runtime as a plain string without a text-import loader.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const source = readFileSync(join(root, "runtime/runtime.js"), "utf8");
const out = `// Generated by scripts/gen-runtime.ts from runtime/runtime.js. Do not edit.\nexport const VIEW_RUNTIME = ${JSON.stringify(source)};\n`;
const target = join(root, "src/runtime.gen.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) {
    console.error("src/runtime.gen.ts is stale: run `bun run gen` in packages/views");
    process.exit(1);
  }
} else writeFileSync(target, out);
